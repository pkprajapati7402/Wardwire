"""Initialize .env file with cryptographically secure random secrets and credentials."""

import os
import secrets
import sys
import bcrypt

ENV_PATH = ".env"
ENV_EXAMPLE = ".env.example"

def generate_secret(n_bytes: int = 32) -> str:
    return secrets.token_hex(n_bytes)

def generate_password(length: int = 16) -> str:
    alphabet = "abcdefghjkmnpqrstuvwxyzABCDEFGHJKLMNPQRSTUVWXYZ23456789!@#$%^&*"
    return "".join(secrets.choice(alphabet) for _ in range(length))

def main():
    force = "--force" in sys.argv
    if os.path.exists(ENV_PATH) and not force:
        print(f"[!] {ENV_PATH} already exists. Use --force to regenerate.")
        return

    admin_pass = generate_password()
    salt = bcrypt.gensalt(rounds=12)
    admin_hash = bcrypt.hashpw(admin_pass.encode("utf-8"), salt).decode("utf-8")

    secret_salt = generate_secret(32)
    jwt_secret = generate_secret(32)
    ingest_key = f"ww_{secrets.token_urlsafe(24)}"

    content = f"""# Auto-generated by scripts/init_env.py
PROJECT_NAME=Wardwire
ENV=development
DEBUG=false

SECRET_SALT={secret_salt}
JWT_SECRET={jwt_secret}
JWT_ALGORITHM=HS256
JWT_EXPIRATION_MINUTES=480
INGEST_API_KEY={ingest_key}
ADMIN_USERNAME=admin
ADMIN_PASSWORD_HASH={admin_hash}

DATABASE_URL=sqlite:///./wardwire.db
REDIS_URL=redis://localhost:6379/0
REDIS_STREAM_NAME=sentinel:events
REDIS_STREAM_GROUP=sentinel_workers

TARGET_URL=http://localhost:8000
API_URL=http://localhost:8001
SIM_ALLOWED_TARGETS=["localhost", "127.0.0.1", "target", "target:8000", "http://localhost:8000", "http://target:8000"]
SIM_MAX_RPS=2000

OPERATING_MODE=shadow
ALERT_BUDGET_HOURLY=20

VOLUMETRIC_Z_THRESHOLD=3.0
CREDENTIAL_STUFFING_FAIL_RATIO=0.65
CREDENTIAL_STUFFING_MIN_FAILURES=15
BOLA_MONOTONIC_RATIO=0.60
BOLA_MIN_OBJECTS=5
SCRAPING_MIN_RESOURCES=20
SCRAPING_CV_THRESHOLD=0.25
PROBING_404_THRESHOLD=10
DATA_EXFIL_BYTES_Z_THRESHOLD=3.0
BENIGN_SUPPRESSION_K=0.85

CARDINALITY_MAX_KEYS=10000

LLM_PROVIDER=none
LLM_MODEL=claude-sonnet-5-5
LLM_BASE_URL=http://localhost:11434

RETENTION_DAYS_ALERTS=7
RETENTION_HOURS_RAW=24
"""

    with open(ENV_PATH, "w", encoding="utf-8") as f:
        f.write(content)

    print("=====================================================")
    print("  Wardwire Initialization Complete")
    print("=====================================================")
    print(f"  .env created with unique secrets.")
    print(f"  Admin Username: admin")
    print(f"  Admin Password: {admin_pass}")
    print(f"  Ingest API Key: {ingest_key}")
    print("=====================================================")
    print("  SAVE THESE CREDENTIALS! They will not be shown again.")
    print("=====================================================\n")

if __name__ == "__main__":
    main()

